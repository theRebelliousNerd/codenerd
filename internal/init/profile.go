// estimateTokens estimates token count for content (chars/4 approximation)
func estimateTokens(content string) int {
	if content == "" {
		return 0
	}
	return (len(content) + 3) / 4
}

// computeContentHash computes a content hash for deduplication.
//
// This was `fmt.Sprintf("%x", len(id+":"+content))` — a length, not a hash. Two
// different atoms of equal length collided, and editing an atom without
// changing its length produced an identical "hash". Now that these atoms are
// ingested into the JIT corpus, content_hash drives cache invalidation there,
// so a collision would serve stale prompt content.
func computeContentHash(id, content string) string {
	sum := sha256.Sum256([]byte(id + ":" + content))
	return hex.EncodeToString(sum[:])
}

// projectAtomToPromptAtom converts a LocalStore prompt atom into the JIT
// compiler's atom type. source_file is deliberately left unset by the loader:
// ReconcilePromptCorpus only deletes rows that claim an owner, so a NULL
// source_file is what marks these as project-owned and keeps them from being
// swept away when the embedded corpus is reconciled.
func projectAtomToPromptAtom(atom *store.PromptAtom) *prompt.PromptAtom {
	return &prompt.PromptAtom{
		ID:          atom.AtomID,
		Version:     atom.Version,
		Content:     atom.Content,
		TokenCount:  atom.TokenCount,
		ContentHash: atom.ContentHash,
		Category:    prompt.AtomCategory(atom.Category),
		Subcategory: atom.Subcategory,
		Languages:   atom.Languages,
		Frameworks:  atom.Frameworks,
		Importance:  prompt.ImportanceUnscored,
		IsMandatory: atom.IsMandatory,
	}
}

// ingestProjectAtomsIntoCorpus writes the atoms built in phase 5b into the JIT
// prompt corpus so prompt assembly can actually select them. It runs after
// ReconcilePromptCorpus so the reconciliation pass can never observe (and
// therefore never delete) a partially written project atom.
func (i *Initializer) ingestProjectAtomsIntoCorpus(ctx context.Context, db *sql.DB) (int, error) {
	i.mu.RLock()
	atoms := i.projectAtoms
	i.mu.RUnlock()

	if len(atoms) == 0 {
		return 0, nil
	}

	loader := prompt.NewAtomLoader(i.embedEngine)
	ingested := 0
	for _, atom := range atoms {
		if atom == nil {
			continue
		}
		if err := loader.StoreAtom(ctx, db, projectAtomToPromptAtom(atom)); err != nil {
			return ingested, fmt.Errorf("ingest project atom %s: %w", atom.AtomID, err)
		}
		ingested++
	}
	return ingested, nil
}

// seedSessionState writes the initial session state when the workspace has
// none, and reports whether it did. An existing session.json is never
// replaced: it is the user's current or resumable session.
func (i *Initializer) seedSessionState(path string) (bool, error) {
	if _, err := os.Stat(path); err == nil {
		return false, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("inspect session state: %w", err)
	}
	state := session.SessionState{
		SessionID:    generateSessionID(),
		StartedAt:    time.Now(),
		LastActiveAt: time.Now(),
		TurnCount:    0,
		Suspended:    false,
	}

	workspace := i.config.Workspace
	if workspace == "" {
		workspace = filepath.Dir(filepath.Dir(path))
	}
	if err := session.SaveSessionState(workspace, &state); err != nil {
		return false, err
	}
	return true, nil
}

// LoadProjectProfile loads the project profile from .nerd/profile.json
func LoadProjectProfile(workspace string) (*ProjectProfile, error) {
	path := filepath.Join(workspace, ".nerd", "profile.json")
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var profile ProjectProfile
	if err := json.Unmarshal(data, &profile); err != nil {
		return nil, err
	}

	return &profile, nil
}

// ListSessionHistories returns the ids of every session that has a chat
// history: the folders under .nerd/sessions holding a session.json.
func ListSessionHistories(workspace string) ([]string, error) {
	sessions := []string{}
	infos, err := sessionlog.List(workspace)
	if err != nil {
		return nil, err
	}
	for _, info := range infos {
		path, err := sessionlog.HistoryPath(workspace, info.ID)
		if err != nil {
			continue
		}
		if st, err := os.Stat(path); err == nil && !st.IsDir() {
			sessions = append(sessions, info.ID)
		}
	}
	return sessions, nil
}

// GetLatestSession returns the most recent session ID.
func GetLatestSession(workspace string) (string, error) {
	state, err := session.LoadSessionState(workspace)
	if err != nil {
		return "", err
	}
	return state.SessionID, nil
}

// IsInitialized checks if the workspace has been initialized.
func IsInitialized(workspace string) bool {
	nerdDir := filepath.Join(workspace, ".nerd")
	profilePath := filepath.Join(nerdDir, "profile.json")

	if _, err := os.Stat(profilePath); err == nil {
		return true
	}
	return false
}

// Helper functions

func generateProjectID(workspace string) string {
	// Simple hash-based ID
	h := uint64(0)
	for _, c := range workspace {
		h = h*31 + uint64(c)
	}
	return fmt.Sprintf("proj_%x", h)[:16]
}

func generateSessionID() string {
	return fmt.Sprintf("sess_%d", time.Now().UnixNano())
}

// sanitizeForMangle converts a string to a valid Mangle name constant.
// Mangle name constants must be lowercase alphanumeric with underscores.
func sanitizeForMangle(s string) string {
	if s == "" {
		return "unknown"
	}

	// Convert to lowercase
	s = strings.ToLower(s)

	// Replace spaces and special characters with underscores
	var result strings.Builder
	for _, c := range s {
		if (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') {
			result.WriteRune(c)
		} else if c == ' ' || c == '-' || c == '.' || c == '/' {
			result.WriteRune('_')
		}
		// Skip other characters
	}

	// Ensure it doesn't start with a number
	sanitized := result.String()
	if len(sanitized) > 0 && sanitized[0] >= '0' && sanitized[0] <= '9' {
		sanitized = "n" + sanitized
	}

	// Remove consecutive underscores and trim
	for strings.Contains(sanitized, "__") {
		sanitized = strings.ReplaceAll(sanitized, "__", "_")
	}
	sanitized = strings.Trim(sanitized, "_")

	if sanitized == "" {
		return "unknown"
	}

	return sanitized
}

// initializePromptDatabase ensures the .nerd/prompts/corpus.db exists and has the
// prompt atom schema required by the JIT prompt compiler.
func (i *Initializer) initializePromptDatabase(ctx context.Context, nerdDir string) error {
	logging.Boot("Initializing prompt corpus database...")

	// Path to the corpus database
	dbPath := filepath.Join(nerdDir, "prompts", "corpus.db")

	// Ensure directory exists
	dir := filepath.Dir(dbPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("failed to create directory %s: %w", dir, err)
	}

	// Seed from baked defaults if available (never overwrites an existing DB).
	if _, err := prompt.MaterializeDefaultPromptCorpus(dbPath); err != nil {
		return fmt.Errorf("failed to materialize default prompt corpus: %w", err)
	}

	// Open database
	db, err := sql.Open("sqlite3", dbPath)
	if err != nil {
		return fmt.Errorf("failed to open database: %w", err)
	}
	defer db.Close()
	sqlpragmas.ApplyDefaultPragmas(db, sqlpragmas.ProfileBulkBuild)

	atomLoader := prompt.NewAtomLoader(nil)
	if err := atomLoader.EnsureSchema(ctx, db); err != nil {
		return fmt.Errorf("failed to ensure corpus schema: %w", err)
	}

	// Best-effort: restore the canonical embedded atom set while preserving
	// project-owned rows. Runtime collection still gives embedded atoms
	// precedence if reconciliation cannot complete. An embedded-corpus load
	// failure is reported here too; it used to skip reconciliation without a
	// word, leaving stale built-in rows in corpus.db as current truth.
	if counts, err := prompt.ReconcileEmbeddedCorpus(ctx, db); err != nil {
		logging.Boot("Warning: failed to reconcile prompt corpus: %v", err)
	} else {
		logging.Boot("Reconciled prompt corpus: upserted=%d deleted=%d retained_embeddings=%d cleared_embeddings=%d", counts.Upserted, counts.Deleted, counts.RetainedEmbeddings, counts.ClearedEmbeddings)
	}

	// Project atoms land after reconciliation so the sweep cannot race them.
	if ingested, err := i.ingestProjectAtomsIntoCorpus(ctx, db); err != nil {
		return fmt.Errorf("failed to ingest project prompt atoms: %w", err)
	} else if ingested > 0 {
		logging.Boot("Ingested %d project prompt atoms into corpus.db", ingested)
		fmt.Fprintf(i.output(), "   ✓ Ingested %d project-specific atoms into the JIT corpus\n", ingested)
	}

	logging.Boot("Prompt corpus database initialized successfully")
	fmt.Fprintln(i.output(), "   ✓ Prompt corpus database ready")
	return nil
}
