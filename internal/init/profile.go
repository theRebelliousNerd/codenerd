// buildProjectProfile constructs the project profile from analysis.
func (i *Initializer) buildProjectProfile() ProjectProfile {
	profile := ProjectProfile{
		ProjectID: generateProjectID(i.config.Workspace),
		Name:      filepath.Base(i.config.Workspace),
		CreatedAt: time.Now(),
		UpdatedAt: time.Now(),
	}

	// Researcher shard removed - using direct detection methods
	// Profile detection is now file-based only

	// Fallback: file-based language detection if kernel didn't provide it
	if profile.Language == "" || profile.Language == "unknown" {
		profile.Language = i.detectLanguageFromFiles()
	}

	// Detect dependencies for agent recommendations
	profile.Dependencies = i.detectDependencies()
	profile.Modules = i.detectModules()

	// Framework is derived from the dependency set, which is why it has to run
	// after detectDependencies.
	profile.Framework = detectFrameworkFromDependencies(profile.Dependencies)

	// Detect build system (B4 enhancement)
	buildSystemInfo := i.detectBuildSystemDetails()
	profile.BuildSystem = buildSystemInfo.Name
	profile.BuildSystemInfo = &buildSystemInfo

	// Detect project type (app vs library) (D2 enhancement)
	profile.ProjectType = i.detectProjectType()

	// Detect entry points (Smart /init detection)
	profile.EntryPoints = i.detectEntryPoints()

	// Set defaults for any missing values
	if profile.Language == "" {
		profile.Language = "unknown"
	}
	if profile.Architecture == "" {
		profile.Architecture = "unknown"
	}

	return profile
}

// saveProfile writes the project profile to disk.
func (i *Initializer) saveProfile(path string, profile ProjectProfile) error {
	data, err := json.MarshalIndent(profile, "", "  ")
	if err != nil {
		return err
	}
	// Atomic: IsInitialized and every later init read this file.
	return atomicfile.WriteFile(path, data, 0o644)
}

// generateFactsFile creates a Mangle facts file for the project.
func (i *Initializer) generateFactsFile(path string, profile ProjectProfile) (int, error) {
	var facts []string

	// Helper to escape strings for Mangle
	escapeString := func(s string) string {
		s = strings.ReplaceAll(s, `\`, `\\`)
		s = strings.ReplaceAll(s, `"`, `\"`)
		s = strings.ReplaceAll(s, "\n", " ")
		s = strings.ReplaceAll(s, "\r", "")
		return s
	}

	// Project identity facts - use escaped strings
	facts = append(facts, fmt.Sprintf(`project_profile("%s", "%s", "%s").`,
		escapeString(profile.ProjectID),
		escapeString(profile.Name),
		escapeString(profile.Description)))

	// Use sanitized name constants for language/framework/architecture
	if profile.Language != "" && profile.Language != "unknown" {
		facts = append(facts, fmt.Sprintf(`project_language(/%s).`, sanitizeForMangle(profile.Language)))
	}

	if profile.Framework != "" && profile.Framework != "unknown" {
		facts = append(facts, fmt.Sprintf(`project_framework(/%s).`, sanitizeForMangle(profile.Framework)))
	}

	if profile.Architecture != "" && profile.Architecture != "unknown" {
		facts = append(facts, fmt.Sprintf(`project_architecture(/%s).`, sanitizeForMangle(profile.Architecture)))
	}

	if profile.BuildSystem != "" {
		facts = append(facts, fmt.Sprintf(`build_system(/%s).`, sanitizeForMangle(profile.BuildSystem)))
	}

	// Pattern facts - sanitize each pattern
	for _, pattern := range profile.Patterns {
		facts = append(facts, fmt.Sprintf(`architectural_pattern(/%s).`, sanitizeForMangle(pattern)))
	}

	// Entry point facts - use escaped strings for paths
	for _, entry := range profile.EntryPoints {
		facts = append(facts, fmt.Sprintf(`entry_point("%s").`, escapeString(entry)))
	}

	// Write facts file
	var content strings.Builder
	content.WriteString("# codeNERD Project Profile Facts\n")
	content.WriteString("# Generated by: nerd init\n")
	content.WriteString(fmt.Sprintf("# Timestamp: %s\n\n", time.Now().Format(time.RFC3339)))

	for _, fact := range facts {
		content.WriteString(fact + "\n")
	}

	// Atomic: every chat boot loads profile.mg, and a torn file fails it.
	if err := atomicfile.WriteFile(path, []byte(content.String()), 0o644); err != nil {
		return 0, err
	}

	return len(facts), nil
}

// initPreferences initializes user preferences.
func (i *Initializer) initPreferences() UserPreferences {
	prefs := UserPreferences{
		Verbosity:        "concise",
		ExplanationLevel: "intermediate",
		RequireTests:     false,
		RequireReview:    false,
	}

	// Apply hints if provided
	for _, hint := range i.config.PreferenceHints {
		switch hint {
		case "table_driven_tests":
			prefs.TestStyle = "table_driven"
		case "conventional_commits":
			prefs.CommitStyle = "conventional"
		case "strict":
			prefs.RequireTests = true
			prefs.RequireReview = true
		case "beginner":
			prefs.ExplanationLevel = "beginner"
		case "expert":
			prefs.ExplanationLevel = "expert"
		}
	}

	return prefs
}

// hintOverriddenPreferenceKeys returns the preferences.json keys that this run's
// PreferenceHints set explicitly. An explicit hint is an instruction for this
// run and therefore outranks whatever is already on disk; every other key is
// merge-preserved.
func (i *Initializer) hintOverriddenPreferenceKeys() map[string]bool {
	keys := make(map[string]bool)
	for _, hint := range i.config.PreferenceHints {
		switch hint {
		case "table_driven_tests":
			keys["test_style"] = true
		case "conventional_commits":
			keys["commit_style"] = true
		case "strict":
			keys["require_tests"] = true
			keys["require_review"] = true
		case "beginner", "expert":
			keys["explanation_level"] = true
		}
	}
	return keys
}

// savePreferences merges the init-owned preference keys into
// .nerd/preferences.json and returns the values that ended up on disk.
//
// This used to be a bare MarshalIndent + WriteFile of a freshly defaulted
// UserPreferences, which truncated the whole document. `.nerd/preferences.json`
// is shared: internal/ux owns the v2.0 blocks (user_journey/onboarding,
// guidance, telemetry, metrics, learned_patterns) and SaveAgentPreferences owns
// agent_selection, which phase 6 of this very run may have just written. So
// `nerd init --force` — whose flag help promises "preserves learned
// preferences" — reset onboarding state, discarded the user's recorded intent
// corrections, dropped their agent accept/reject history, and reverted every
// autopoiesis-learned style key to its default.
//
// The file is now a merge target: keys already present win, missing keys are
// seeded with the computed default, keys this run was explicitly hinted about
// are overwritten, and unknown keys are carried through untouched. A corrupt
// file is a hard error rather than an excuse to clobber (same rule as
// SaveAgentPreferences).
func (i *Initializer) savePreferences(path string, prefs UserPreferences) (UserPreferences, error) {
	merged := make(map[string]any)

	existingData, readErr := os.ReadFile(path)
	if readErr != nil && !os.IsNotExist(readErr) {
		return prefs, fmt.Errorf("read existing preferences: %w", readErr)
	}
	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &merged); err != nil {
			return prefs, fmt.Errorf("existing preferences.json is corrupt (refusing to overwrite): %w", err)
		}
	}

	defaultsJSON, err := json.Marshal(prefs)
	if err != nil {
		return prefs, err
	}
	defaults := make(map[string]any)
	if err := json.Unmarshal(defaultsJSON, &defaults); err != nil {
		return prefs, err
	}

	overrides := i.hintOverriddenPreferenceKeys()
	for key, value := range defaults {
		if _, present := merged[key]; present && !overrides[key] {
			continue
		}
		merged[key] = value
	}

	data, err := json.MarshalIndent(merged, "", "  ")
	if err != nil {
		return prefs, err
	}
	// Atomic, not truncating. This is a read-modify-write over a file shared
	// with internal/ux and SaveAgentPreferences, and the merge above treats a
	// corrupt existing file as a hard error — so a torn write here does not
	// just lose the merge, it wedges every later `nerd init` for this
	// workspace behind a file it refuses to parse.
	if err := atomicfile.WriteFile(path, data, 0644); err != nil {
		return prefs, err
	}

	// Report what is actually on disk, not what we would have written; the
	// summary and InitResult must not claim defaults the merge rejected.
	effective := prefs
	if err := json.Unmarshal(data, &effective); err != nil {
		return prefs, nil
	}
	return effective, nil
}

// populateProjectAtoms builds the project-specific prompt atoms and keeps
// them for phase 5c, which ingests them into .nerd/prompts/corpus.db, the
// corpus the JIT compiler selects from. They used to be written to
// knowledge.db as well, where nothing reads prompt atoms.
func (i *Initializer) populateProjectAtoms(profile ProjectProfile) error {
	atoms := i.buildProjectAtoms(profile)
	i.mu.Lock()
	i.projectAtoms = atoms
	i.mu.Unlock()
	fmt.Fprintf(i.output(), "   ✓ Built %d project-specific prompt atoms for the corpus\n", len(atoms))
	return nil
}

