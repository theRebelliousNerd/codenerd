package system

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"codenerd/internal/types"
)

// The coder policy (coder_*.mg) judged a file nothing named: coder_target and
// coder_task were inputs of a CoderShard that no longer runs. They are derived
// now from the turn's intent and the edit in flight, and three consumers act on
// the conclusions: the context compiler (context_relevant), the prompt compiler
// (injectable_context rows for the coder shard) and the constitution (permitted
// refuses a write the coder policy bars). This runs the real sharded kernel.
func TestCoderPolicyReachesItsConsumersOnTheShardedKernel(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping full Cortex boot in -short mode")
	}
	ws := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(ws, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/app\n\ngo 1.26\n")
	write("core/core.go", "package core\n\nfunc Do() {}\n")
	write("core/core_test.go", "package core\n\nimport \"testing\"\n\nfunc TestDo(t *testing.T) { Do() }\n")
	for i := 0; i < 7; i++ { // seven importers: a high-impact file
		write(fmt.Sprintf("p%d/p.go", i), fmt.Sprintf("package p%d\n\nimport \"example.com/app/core\"\n\nfunc Run() { core.Do() }\n", i))
	}

	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	cortex, err := BootCortex(ctx, ws, "", nil)
	if err != nil {
		t.Fatalf("BootCortex: %v", err)
	}
	defer requireWorkspaceReleased(t, cortex, ws)

	intent := types.Fact{Predicate: "user_intent", Args: []any{
		types.MangleAtom("/current_intent"), types.MangleAtom("/mutation"), types.MangleAtom("/fix"), "core/core.go", "fix the nil crash"}}
	if err := cortex.Kernel.Assert(intent); err != nil {
		t.Fatal(err)
	}

	// The compiler's relevance: the target, the test beside it, the importers.
	relevant, err := cortex.Kernel.Query("context_relevant")
	if err != nil {
		t.Fatal(err)
	}
	if !factWith(relevant, "core/core.go", "/p100") {
		t.Errorf("the file under change is the most relevant context: %v", relevant)
	}
	if !factWith(relevant, "core/core_test.go", "/p75") {
		t.Errorf("its test is relevant context: %v", relevant)
	}
	if !factWith(relevant, "p3/p.go", "/p60") {
		t.Errorf("a file that imports it is relevant context: %v", relevant)
	}

	// What the prompt says, as the JIT compiler reads it (injectable_context for
	// the "coder" shard): the language conventions, the kind of change, the impact.
	rows, err := cortex.Kernel.Query("injectable_context")
	if err != nil {
		t.Fatal(err)
	}
	var lines []string
	for _, f := range rows {
		if len(f.Args) >= 2 && types.ExtractString(f.Args[0]) == "coder" {
			lines = append(lines, types.ExtractString(f.Args[1]))
		}
	}
	joined := strings.Join(lines, "\n")
	for _, want := range []string{
		"return errors, don't panic",       // Go convention, from the file's extension
		"Reproduce the failure first",      // a /fix
		"core/core.go is imported by many", // impact
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("the coder's prompt rows lack %q:\n%s", want, joined)
		}
	}
	if strings.Contains(joined, "snake_case") {
		t.Errorf("another language's conventions must not reach a Go file:\n%s", joined)
	}

	// What may be edited: generated, vendored and project-forbidden paths are
	// refused; an ordinary file is permitted.
	if err := cortex.Kernel.AssertBatch([]types.Fact{
		{Predicate: "generated_code", Args: []any{"api/api.pb.go", types.MangleAtom("/protoc"), "Code generated by protoc. DO NOT EDIT."}},
		{Predicate: "project_forbidden_path", Args: []any{"secrets/", "keep out"}},
	}); err != nil {
		t.Fatal(err)
	}
	pending := func(id, target string) types.Fact {
		return types.Fact{Predicate: "pending_action", Args: []any{id, types.MangleAtom("/edit_file"), target, "{}", int64(1)}}
	}
	targets := []string{"core/core.go", "api/api.pb.go", "vendor/lib/lib.go", "secrets/key.txt"}
	var facts []types.Fact
	for i, tg := range targets {
		facts = append(facts, pending(fmt.Sprintf("a%d", i), tg))
	}
	if err := cortex.Kernel.AssertBatch(facts); err != nil {
		t.Fatal(err)
	}
	permitted, err := cortex.Kernel.Query("permitted")
	if err != nil {
		t.Fatal(err)
	}
	allowed := map[string]bool{}
	for _, f := range permitted {
		if len(f.Args) >= 2 {
			allowed[types.ExtractString(f.Args[1])] = true
		}
	}
	if !allowed["core/core.go"] {
		t.Errorf("an ordinary source file may be edited: %v", allowed)
	}
	for _, barred := range targets[1:] {
		if allowed[barred] {
			t.Errorf("%s must be refused: %v", barred, allowed)
		}
	}
}
