// runWhatIf runs counterfactual analysis.
// Kernel implications are the deterministic, always-complete result. Optional
// LLM elaboration uses a short direct Complete call — never SpawnTask(researcher),
// which previously hung after the first kernel line when the JIT spawn path stalled.
func runWhatIf(cmd *cobra.Command, args []string) error {
	// Overall budget: boot + kernel + optional LLM elaboration.
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	change := strings.Join(args, " ")

	fmt.Printf("🔮 What-If Analysis\n")
	fmt.Printf("❓ Change: %s\n", change)
	fmt.Println(strings.Repeat("─", 60))

	// Resolve API key
	key := resolveAPIKey(apiKey, workspace)

	// Boot Cortex
	cortex, err := coresys.GetOrBootCortex(ctx, workspace, key, nil)
	if err != nil {
		return fmt.Errorf("failed to boot cortex: %w", err)
	}
	defer cortex.Close()

	// Assert the hypothetical to kernel
	hypFact := core.Fact{
		Predicate: "hypothetical",
		Args:      []any{change},
	}
	if err := cortex.Kernel.Assert(hypFact); err != nil {
		logging.KernelWarn("failed to assert hypothetical fact: %v", err)
	}

	// Query implications
	implications, _ := cortex.Kernel.Query("derives_from_hypothetical")

	fmt.Println("📊 Kernel Implications:")
	if len(implications) > 0 {
		for _, imp := range implications {
			fmt.Printf("   - %s\n", imp.String())
		}
	} else {
		fmt.Println("   (no derived implications)")
	}
	fmt.Println()

	// Bounded LLM elaboration (optional). Fail soft so the command always exits.
	if cortex.LLMClient == nil {
		fmt.Println("📋 Analysis: (skipped — no LLM client)")
		return nil
	}

	prompt := fmt.Sprintf(
		"Analyze the implications of this hypothetical change in 6-10 bullet points:\n\n%s\n\nCover: affected systems, breakage risk, improvements, and mitigations.",
		change,
	)
	analysisCtx, analysisCancel := context.WithTimeout(ctx, 45*time.Second)
	defer analysisCancel()

	fmt.Println("📋 Analysis:")
	result, err := cortex.LLMClient.Complete(analysisCtx, prompt)
	if err != nil {
		if analysisCtx.Err() != nil {
			fmt.Println("   (analysis timed out; kernel implications above are complete)")
		} else {
			fmt.Printf("   Analysis failed: %v\n", err)
		}
		return nil
	}
	fmt.Println(result)
	return nil
}

// runLogicQuery shows kernel facts
func runLogicQuery(cmd *cobra.Command, args []string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	fmt.Printf("🧠 Mangle Kernel Facts\n")

	// Resolve API key
	key := resolveAPIKey(apiKey, workspace)

	// Boot Cortex
	cortex, err := coresys.GetOrBootCortex(ctx, workspace, key, nil)
	if err != nil {
		return fmt.Errorf("failed to boot cortex: %w", err)
	}
	defer cortex.Close()

	// With no predicate, show what the kernel holds.
	//
	// The default used to be the literal string "*", which is not a wildcard
	// the kernel understands — it is simply a predicate name nothing matches.
	// So bare `nerd logic` printed "Found 0 facts" on a kernel holding 3,737
	// file_topology and 10,510 symbol_graph facts, and read as an empty brain.
	if len(args) == 0 {
		return printKernelFactSummary(cortex)
	}

	predicate := args[0]
	fmt.Printf("🔍 Query: %s\n", predicate)
	fmt.Println(strings.Repeat("─", 60))

	// Query facts
	facts, err := cortex.Kernel.Query(predicate)
	if err != nil {
		return fmt.Errorf("query failed: %w", err)
	}

	fmt.Printf("📊 Found %d facts:\n\n", len(facts))
	for i, fact := range facts {
		if i >= 50 {
			fmt.Printf("... and %d more\n", len(facts)-50)
			break
		}
		fmt.Printf("  %s\n", fact.String())
	}

	return nil
}

// printKernelFactSummary reports which predicates hold facts and how many,
// which is the useful answer to a bare `nerd logic`. Naming a predicate still
// lists its facts.
func printKernelFactSummary(cortex *coresys.Cortex) error {
	fmt.Println("🔍 Summary (pass a predicate to list its facts)")
	fmt.Println(strings.Repeat("─", 60))

	byPredicate, err := cortex.Kernel.QueryAll()
	if err != nil {
		return fmt.Errorf("failed to read kernel facts: %w", err)
	}

	counts := make(map[string]int, len(byPredicate))
	for predicate, facts := range byPredicate {
		counts[predicate] = len(facts)
	}

	if len(counts) == 0 {
		fmt.Println("📊 The kernel holds no facts.")
		fmt.Println("   Run 'nerd scan' to index the workspace.")
		return nil
	}

	type predCount struct {
		name  string
		count int
	}
	ordered := make([]predCount, 0, len(counts))
	total := 0
	for name, count := range counts {
		ordered = append(ordered, predCount{name, count})
		total += count
	}
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].count != ordered[j].count {
			return ordered[i].count > ordered[j].count
		}
		return ordered[i].name < ordered[j].name
	})

	fmt.Printf("📊 %d facts across %d predicates:\n\n", total, len(ordered))
	const shown = 25
	for i, pc := range ordered {
		if i >= shown {
			fmt.Printf("\n... and %d more predicates\n", len(ordered)-shown)
			break
		}
		fmt.Printf("  %-40s %7d\n", pc.name, pc.count)
	}

	return nil
}

