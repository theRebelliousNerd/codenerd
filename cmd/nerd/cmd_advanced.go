// runToolCommand handles tool management
func runToolCommand(cmd *cobra.Command, args []string) error {
	if len(args) == 0 {
		fmt.Println("Usage: nerd tool <list|run|info|generate> [args]")
		return nil
	}

	// Honour the documented --timeout flag rather than a hardcoded ceiling.
	//
	// This was 5 minutes flat. `nerd tool generate` runs a whole Ouroboros
	// pipeline behind that one deadline -- detect the need, generate the code
	// via LLM, compile it, register it -- and the codegen call alone routinely
	// exceeds five minutes on a reasoning model. The command advertises
	// `--timeout` in its own help text (default 25m) and then ignored it, so
	// every generation died with a bare "context deadline exceeded" that named
	// neither the real limit nor the flag that was supposed to control it.
	toolCtxTimeout := timeout
	if toolCtxTimeout <= 0 {
		toolCtxTimeout = 25 * time.Minute
	}
	ctx, cancel := context.WithTimeout(context.Background(), toolCtxTimeout)
	defer cancel()

	// Resolve API key
	key := resolveAPIKey(apiKey, workspace)

	// Boot Cortex
	cortex, err := coresys.GetOrBootCortex(ctx, workspace, key, nil)
	if err != nil {
		return fmt.Errorf("failed to boot cortex: %w", err)
	}
	defer cortex.Close()

	subCmd := args[0]
	switch subCmd {
	case "list":
		fmt.Println("🔧 Generated Tools (Ouroboros)")
		fmt.Println(strings.Repeat("─", 60))

		// Prefer the durable Ouroboros registry (survives across CLI process
		// restarts via disk restore). Kernel tool_registered facts alone are
		// session-local and frequently empty after a fresh boot even when
		// tools exist on disk — the live-matrix hollow success.
		seen := map[string]bool{}
		listed := 0
		if cortex.Orchestrator != nil {
			for _, tool := range cortex.Orchestrator.ListTools() {
				if tool.Name == "" || seen[tool.Name] {
					continue
				}
				seen[tool.Name] = true
				listed++
				desc := tool.Description
				if desc != "" {
					fmt.Printf("  - %s: %s\n", tool.Name, desc)
				} else {
					fmt.Printf("  - %s\n", tool.Name)
				}
			}
		}
		// Also surface any kernel-only registrations from this session.
		kernelTools, _ := cortex.Kernel.Query("tool_registered")
		for _, tool := range kernelTools {
			if len(tool.Args) == 0 {
				continue
			}
			name := types.ExtractString(tool.Args[0])
			if name == "" || seen[name] {
				continue
			}
			seen[name] = true
			listed++
			fmt.Printf("  - %s\n", name)
		}
		if listed == 0 {
			fmt.Println("No tools generated yet.")
			fmt.Println("\nUse 'nerd tool generate <description>' to create one.")
		}

	case "run":
		if len(args) < 2 {
			return fmt.Errorf("usage: nerd tool run <name> [input]")
		}
		toolName := args[1]
		toolInput := ""
		if len(args) > 2 {
			toolInput = strings.Join(args[2:], " ")
		}

		fmt.Printf("🔧 Running tool: %s\n", toolName)
		fmt.Println(strings.Repeat("─", 60))

		// Find tool binary path from kernel facts
		var binaryPath string
		allBinaries, _ := cortex.Kernel.Query("tool_binary_path")
		for _, b := range allBinaries {
			if len(b.Args) >= 2 && types.ExtractString(b.Args[0]) == toolName {
				binaryPath = types.ExtractString(b.Args[1])
				break
			}
		}

		if binaryPath == "" {
			return fmt.Errorf("tool '%s' not found. Run 'nerd tool list' to see available tools", toolName)
		}

		// SECURITY FIX: Prevent command injection and path traversal
		// Ensure the binary is executed from the .nerd/tools/.compiled directory
		ws := workspace
		if ws == "" {
			ws, _ = os.Getwd()
		}
		expectedDir := filepath.Join(ws, ".nerd", "tools", ".compiled")

		absExpectedDir, err := filepath.Abs(expectedDir)
		if err != nil {
			return fmt.Errorf("failed to resolve expected tools directory: %w", err)
		}

		absBinaryPath, err := filepath.Abs(binaryPath)
		if err != nil {
			return fmt.Errorf("failed to resolve binary path: %w", err)
		}

		relPath, err := filepath.Rel(absExpectedDir, absBinaryPath)
		if err != nil || strings.HasPrefix(relPath, "..") || relPath == ".." || filepath.IsAbs(relPath) {
			return fmt.Errorf("security error: binary path '%s' is outside expected directory '%s'", binaryPath, expectedDir)
		}

		if _, err := os.Stat(absBinaryPath); os.IsNotExist(err) {
			return fmt.Errorf("tool binary not found at '%s'", absBinaryPath)
		}

		// Execute tool binary directly
		toolCmd := exec.CommandContext(ctx, absBinaryPath)
		if toolInput != "" {
			toolCmd.Stdin = strings.NewReader(toolInput)
		}
		toolCmd.Stdout = os.Stdout
		toolCmd.Stderr = os.Stderr

		if err := toolCmd.Run(); err != nil {
			return fmt.Errorf("tool execution failed: %w", err)
		}

	case "info":
		if len(args) < 2 {
			return fmt.Errorf("usage: nerd tool info <name>")
		}
		toolName := args[1]

		fmt.Printf("🔧 Tool Info: %s\n", toolName)
		fmt.Println(strings.Repeat("─", 60))

		// Query tool details (filter results in Go since kernel.Query returns all facts)
		allDetails, _ := cortex.Kernel.Query("tool_description")
		for _, d := range allDetails {
			if len(d.Args) >= 2 && types.ExtractString(d.Args[0]) == toolName {
				fmt.Printf("Description: %v\n", d.Args[1])
				break
			}
		}

		allBinaries, _ := cortex.Kernel.Query("tool_binary_path")
		for _, b := range allBinaries {
			if len(b.Args) >= 2 && types.ExtractString(b.Args[0]) == toolName {
				fmt.Printf("Binary: %v\n", b.Args[1])
				break
			}
		}

	case "generate":
		if len(args) < 2 {
			return fmt.Errorf("usage: nerd tool generate <description>")
		}
		description := strings.Join(args[1:], " ")

		fmt.Printf("🔧 Generating Tool\n")
		fmt.Printf("📝 Description: %s\n", description)
		fmt.Println(strings.Repeat("─", 60))

		// Use Ouroboros via the autopoiesis orchestrator — the durable path
		// that writes, compiles, registers, and asserts tool_registered.
		// SpawnTask(tool_generator) previously returned planning prose
		// ("Generated self-tool X") with exit 0 while tool list stayed empty.
		if cortex.Orchestrator == nil {
			return fmt.Errorf("tool generation failed: autopoiesis orchestrator not initialized")
		}

		need, err := cortex.Orchestrator.DetectToolNeed(ctx, description)
		if err != nil {
			return fmt.Errorf("tool generation failed (detect): %w", err)
		}
		if need == nil {
			// Explicit CLI generate is authoritative — never no-op on weak detection.
			need = buildCLIToolNeed(description)
		}

		fmt.Printf("Detected need: %s\n", need.Name)
		fmt.Printf("Purpose: %s\n", need.Purpose)
		fmt.Println(strings.Repeat("─", 60))

		loopRes := cortex.Orchestrator.ExecuteOuroborosLoop(ctx, need)
		if loopRes == nil {
			return fmt.Errorf("tool generation failed: ouroboros returned nil result")
		}
		if !loopRes.Success {
			errMsg := loopRes.Error
			if errMsg == "" {
				errMsg = fmt.Sprintf("stopped at stage %v", loopRes.Stage)
			}
			return fmt.Errorf("tool generation failed: %s", errMsg)
		}
		if strings.TrimSpace(loopRes.ToolName) == "" {
			return fmt.Errorf("tool generation failed: empty tool name after claimed success")
		}

		// Verify durability: tool must appear in the registry ListTools sees.
		found := cortex.Orchestrator.HasGeneratedTool(loopRes.ToolName)
		if !found {
			for _, t := range cortex.Orchestrator.ListTools() {
				if t.Name == loopRes.ToolName {
					found = true
					break
				}
			}
		}
		if !found {
			return fmt.Errorf(
				"tool generation hollow success blocked: %q not visible to tool list after generate",
				loopRes.ToolName,
			)
		}

		fmt.Printf("✅ Tool registered: %s\n", loopRes.ToolName)
		if loopRes.CompileResult != nil && loopRes.CompileResult.OutputPath != "" {
			fmt.Printf("Binary: %s\n", loopRes.CompileResult.OutputPath)
		}
		fmt.Printf("Duration: %v\n", loopRes.Duration)
		fmt.Println("\nUse 'nerd tool list' to confirm, 'nerd tool run <name>' to execute.")

	default:
		return fmt.Errorf("unknown subcommand: %s (use list, run, info, or generate)", subCmd)
	}

	return nil
}

// buildCLIToolNeed constructs an authoritative ToolNeed for explicit
// `nerd tool generate` requests when DetectToolNeed returns nil.
func buildCLIToolNeed(description string) *autopoiesis.ToolNeed {
	return &autopoiesis.ToolNeed{
		Name:       toolNameFromDescription(description),
		Purpose:    strings.TrimSpace(description),
		Reasoning:  "cli_tool_generate",
		Confidence: 1.0,
		Priority:   1.0,
	}
}

var nonIdentRunes = regexp.MustCompile(`[^a-z0-9_]+`)

// toolNameFromDescription derives a stable snake_case tool name from free text.
func toolNameFromDescription(description string) string {
	s := strings.ToLower(strings.TrimSpace(description))
	if s == "" {
		return "generated_tool"
	}
	// Keep alphanumerics; collapse the rest to underscores.
	var b strings.Builder
	prevUnderscore := false
	for _, r := range s {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
			prevUnderscore = false
			continue
		}
		if !prevUnderscore {
			b.WriteByte('_')
			prevUnderscore = true
		}
	}
	name := strings.Trim(b.String(), "_")
	name = nonIdentRunes.ReplaceAllString(name, "_")
	name = strings.Trim(name, "_")
	if name == "" {
		return "generated_tool"
	}
	// Cap length so binary/path names stay manageable.
	if len(name) > 48 {
		name = name[:48]
		name = strings.Trim(name, "_")
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "tool_" + name
	}
	return name
}

// runJITStatus shows JIT compiler status
func runJITStatus(cmd *cobra.Command, args []string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	fmt.Printf("⚡ JIT Prompt Compiler Status\n")
	fmt.Println(strings.Repeat("─", 60))

	// Resolve API key
	key := resolveAPIKey(apiKey, workspace)

	// Boot Cortex
	cortex, err := coresys.GetOrBootCortex(ctx, workspace, key, nil)
	if err != nil {
		return fmt.Errorf("failed to boot cortex: %w", err)
	}
	defer cortex.Close()

	// Get compiler stats
	if cortex.JITCompiler != nil {
		stats := cortex.JITCompiler.GetStats()
		fmt.Printf("Embedded Atoms:   %d\n", stats.EmbeddedAtomCount)
		fmt.Printf("Project Atoms:    %d\n", stats.ProjectAtomCount)
		fmt.Printf("Shard DBs:        %d\n", stats.ShardDBCount)
		fmt.Printf("Compilations:     %d\n", stats.TotalCompilations)
		fmt.Printf("Avg Time (ms):    %.2f\n", stats.AverageTimeMs)
	} else {
		fmt.Println("JIT Compiler not initialized")
	}

	// Show prompt atoms currently asserted in the kernel.
	//
	// This is NOT the corpus. prompt_atom facts are asserted per compile by the
	// selector (internal/prompt/selector.go, buildContextFacts + AssertBatch),
	// so on a freshly booted process — which `nerd jit` always is — the count is
	// necessarily zero. Printed bare next to "Embedded Atoms: 892" it read as
	// "the corpus failed to load", which is the opposite of the truth.
	//
	// The error was also being discarded, making a failed query indistinguishable
	// from an empty one. Same defect family as the glassbox and transparency
	// predicates fixed earlier: a diagnostic whose only possible answer here is
	// "nothing", phrased as a fact about the system.
	atoms, err := cortex.Kernel.Query("prompt_atom")
	switch {
	case err != nil:
		fmt.Printf("\nPrompt Atoms In Kernel: query failed (%v)\n", err)
	case len(atoms) == 0:
		fmt.Printf("\nPrompt Atoms In Kernel: 0 — none asserted yet.\n")
		fmt.Printf("  Atoms are asserted per compile, and this process has run %d.\n", statsCompilations(cortex))
		fmt.Printf("  The %d embedded atoms above are the corpus and are unaffected.\n", embeddedCount(cortex))
	default:
		fmt.Printf("\nPrompt Atoms In Kernel: %d\n", len(atoms))
		if len(atoms) <= 10 {
			for _, atom := range atoms {
				fmt.Printf("  - %v\n", atom.Args[0])
			}
		}
	}

	return nil
}

// statsCompilations and embeddedCount read the JIT stats defensively so the
// explanatory lines in `nerd jit` cannot themselves panic on a nil compiler.
func statsCompilations(cortex *coresys.Cortex) int {
	if cortex == nil || cortex.JITCompiler == nil {
		return 0
	}
	return int(cortex.JITCompiler.GetStats().TotalCompilations)
}

func embeddedCount(cortex *coresys.Cortex) int {
	if cortex == nil || cortex.JITCompiler == nil {
		return 0
	}
	return int(cortex.JITCompiler.GetStats().EmbeddedAtomCount)
}
